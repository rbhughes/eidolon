"""Process control for live monitoring and recording.

Audio path: rtl_fm (FM demod, raw s16le PCM on stdout) piped into paplay
(PipeWire's PulseAudio-compatible player) for live listening, or captured
to a .wav file for recording. Both are CLI tools shelled out to -- see
doctor.py for why we avoid the pyrtlsdr bindings.
"""

from __future__ import annotations

import io
import json
import os
import random
import signal
import subprocess
import threading
import time
import wave
from collections import deque
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
STATE_DIR = PROJECT_ROOT / ".run"
STATE_FILE = STATE_DIR / "session.json"
HOTSPOTS_FILE = STATE_DIR / "hotspots.json"

# User-editable list of internet radio stations for the "stream" sweep
# source -- unlike hotspots.json (generated by scan()), this is checked into
# the repo as a starting seed list.
STREAMS_FILE = PROJECT_ROOT / "streams.json"

DEFAULT_FREQ = "100.0M"
DEFAULT_VOLUME = 65536  # PulseAudio/PipeWire "normal" (unity) volume
RF_SAMPLE_RATE_ARG = "200k"
AUDIO_RATE_ARG = "48k"
AUDIO_RATE_HZ = 48000

# US FM broadcast channels sit every 200kHz starting at 88.1 MHz (odd tenths
# only) -- hopping off this grid guarantees landing between stations.
FM_CHANNEL_SPACING_HZ = 200_000
FM_CHANNEL_BASE_HZ = 88_100_000


def _rtl_fm_cmd(freq: str) -> list[str]:
    return ["rtl_fm", "-f", freq, "-M", "fm", "-s", RF_SAMPLE_RATE_ARG, "-r", AUDIO_RATE_ARG, "-"]


def _ffmpeg_stream_cmd(url: str) -> list[str]:
    return [
        "ffmpeg",
        "-nostdin",
        "-loglevel",
        "error",
        "-i",
        url,
        "-f",
        "s16le",
        "-ar",
        str(AUDIO_RATE_HZ),
        "-ac",
        "1",
        "-",
    ]


def _random_valid_channel(band: tuple[float, float]) -> float:
    """A random frequency on the real FM channel grid within band."""
    low, high = int(band[0]), int(band[1])
    first = FM_CHANNEL_BASE_HZ + FM_CHANNEL_SPACING_HZ * max(
        0, -(-(low - FM_CHANNEL_BASE_HZ) // FM_CHANNEL_SPACING_HZ)
    )
    n_channels = max(1, int((high - first) // FM_CHANNEL_SPACING_HZ) + 1)
    return float(first + random.randrange(n_channels) * FM_CHANNEL_SPACING_HZ)


def scan(
    band: tuple[float, float] = (88.0e6, 108.0e6),
    resolution_hz: float = 50_000,
    integration_seconds: int = 20,
    min_db_above_median: float = 6.0,
    top_n: int = 20,
) -> list[dict]:
    """Sweep `band` with rtl_power and save the strongest peaks as hotspots
    for sweep() to bias hops towards. Returns the peaks found."""
    import csv
    import tempfile

    low, high = band
    with tempfile.NamedTemporaryFile(suffix=".csv", delete=False) as tmp:
        csv_path = Path(tmp.name)
    try:
        subprocess.run(
            ["rtl_power", "-f", f"{int(low)}:{int(high)}:{int(resolution_hz)}", "-i", str(integration_seconds), "-1", str(csv_path)],
            capture_output=True,
            timeout=integration_seconds + 60,
        )
        rows: list[tuple[float, float]] = []
        with open(csv_path) as f:
            for line in f:
                parts = [p.strip() for p in line.strip().split(",")]
                if len(parts) < 7:
                    continue
                hz_low, hz_step = float(parts[2]), float(parts[4])
                for i, db_str in enumerate(parts[6:]):
                    rows.append((hz_low + i * hz_step, float(db_str)))
    finally:
        csv_path.unlink(missing_ok=True)

    if not rows:
        return []

    median_db = sorted(db for _, db in rows)[len(rows) // 2]
    threshold = median_db + min_db_above_median

    rows.sort(key=lambda r: -r[1])
    peaks: list[dict] = []
    for freq, db in rows:
        if db < threshold:
            break
        if any(abs(freq - p["freq_hz"]) < FM_CHANNEL_SPACING_HZ for p in peaks):
            continue
        peaks.append({"freq_hz": freq, "db": db})
        if len(peaks) >= top_n:
            break

    STATE_DIR.mkdir(exist_ok=True)
    HOTSPOTS_FILE.write_text(json.dumps(peaks))
    return peaks


def load_hotspots() -> list[dict]:
    if not HOTSPOTS_FILE.exists():
        return []
    try:
        return json.loads(HOTSPOTS_FILE.read_text())
    except (json.JSONDecodeError, OSError):
        return []


def _make_hop_picker(source: str, band: tuple[float, float], hotspot_bias: float) -> Callable[[], tuple[str, list[str]]]:
    """Build a closure that picks the next hop's (label, capture command).

    Shared by sweep() and ScrubSession so both sources (SDR frequencies,
    internet radio stations) are only implemented once.
    """
    if source not in ("sdr", "stream"):
        raise ValueError(f"unknown source: {source!r} (expected 'sdr' or 'stream')")
    hotspots = load_hotspots() if source == "sdr" and hotspot_bias > 0 else []
    streams = load_streams() if source == "stream" else []
    if source == "stream" and not streams:
        raise RuntimeError(f"no stations configured -- add some to {STREAMS_FILE}")
    stream_weights = [s.get("weight", 1) for s in streams]

    def _next_hop() -> tuple[str, list[str]]:
        if source == "stream":
            station = random.choices(streams, weights=stream_weights, k=1)[0]
            return station["name"], _ffmpeg_stream_cmd(station["url"])
        if hotspots and random.random() < hotspot_bias:
            freq_hz = random.choice(hotspots)["freq_hz"]
        else:
            freq_hz = _random_valid_channel(band)
        freq = f"{freq_hz / 1e6:.1f}M"
        return freq, _rtl_fm_cmd(freq)

    return _next_hop


def _capture_chunk(cmd: list[str], chunk_bytes_target: int, player_stdin, max_wait: float) -> bytes:
    """Run `cmd`, streaming its stdout into `player_stdin` (if given) while
    collecting up to `chunk_bytes_target` bytes. A watchdog timer bounds
    worst-case hang if the source stalls (stream connections can; SDR
    tuning rarely does, but the safety net is free)."""
    proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    assert proc.stdout is not None
    watchdog = threading.Timer(max_wait, proc.kill)
    watchdog.start()
    collected = bytearray()
    try:
        while len(collected) < chunk_bytes_target:
            data = proc.stdout.read(4096)
            if not data:
                break
            collected.extend(data)
            if player_stdin is not None:
                try:
                    player_stdin.write(data)
                except BrokenPipeError:
                    pass
    finally:
        watchdog.cancel()
        proc.terminate()
        try:
            proc.wait(timeout=1)
        except subprocess.TimeoutExpired:
            proc.kill()
    return bytes(collected)


def load_streams() -> list[dict]:
    """Load the configured internet radio stations (see STREAMS_FILE)."""
    if not STREAMS_FILE.exists():
        return []
    try:
        return json.loads(STREAMS_FILE.read_text())
    except (json.JSONDecodeError, OSError):
        return []


def _pcm_to_wav_bytes(pcm: bytes, rate: int = AUDIO_RATE_HZ) -> bytes:
    buf = io.BytesIO()
    with wave.open(buf, "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(rate)
        wav.writeframes(pcm)
    return buf.getvalue()


def _pid_alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except OSError:
        return False
    return True


def _read_state() -> dict | None:
    if not STATE_FILE.exists():
        return None
    try:
        return json.loads(STATE_FILE.read_text())
    except (json.JSONDecodeError, OSError):
        return None


def _write_state(data: dict) -> None:
    STATE_DIR.mkdir(exist_ok=True)
    STATE_FILE.write_text(json.dumps(data))


def is_running() -> dict | None:
    """Return the current session's state if both processes are still alive."""
    state = _read_state()
    if state is None:
        return None
    if _pid_alive(state["rtl_fm_pid"]) and _pid_alive(state["player_pid"]):
        return state
    STATE_FILE.unlink(missing_ok=True)
    return None


def start(freq: str = DEFAULT_FREQ, volume: int = DEFAULT_VOLUME) -> dict:
    existing = is_running()
    if existing is not None:
        raise RuntimeError(f"already running at {existing['freq']} -- run stop first")

    rtl_fm = subprocess.Popen(
        _rtl_fm_cmd(freq),
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )
    assert rtl_fm.stdout is not None
    player = subprocess.Popen(
        [
            "paplay",
            "--raw",
            f"--rate={AUDIO_RATE_HZ}",
            "--format=s16le",
            "--channels=1",
            "--client-name=spiritbox",
            f"--volume={volume}",
        ],
        stdin=rtl_fm.stdout,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )
    rtl_fm.stdout.close()  # player now owns the read end

    state = {
        "freq": freq,
        "volume": volume,
        "rtl_fm_pid": rtl_fm.pid,
        "player_pid": player.pid,
        "started_at": time.time(),
    }
    _write_state(state)
    return state


def _terminate(pid: int, timeout: float = 2.0) -> None:
    if not _pid_alive(pid):
        return
    try:
        os.kill(pid, signal.SIGTERM)
    except OSError:
        return
    deadline = time.time() + timeout
    while time.time() < deadline:
        if not _pid_alive(pid):
            return
        time.sleep(0.1)
    try:
        os.kill(pid, signal.SIGKILL)
    except OSError:
        pass


def stop() -> dict | None:
    state = _read_state()
    if state is None:
        return None
    _terminate(state["player_pid"])
    _terminate(state["rtl_fm_pid"])
    STATE_FILE.unlink(missing_ok=True)
    return state


def record(path: Path, seconds: float, freq: str = DEFAULT_FREQ) -> Path:
    if is_running() is not None:
        raise RuntimeError("live monitor is running -- run stop first")

    proc = subprocess.Popen(_rtl_fm_cmd(freq), stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    assert proc.stdout is not None

    chunks: list[bytes] = []
    deadline = time.time() + seconds
    try:
        while time.time() < deadline:
            chunk = proc.stdout.read(65536)
            if not chunk:
                break
            chunks.append(chunk)
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=2)
        except subprocess.TimeoutExpired:
            proc.kill()

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(_pcm_to_wav_bytes(b"".join(chunks)))
    return path


def sweep(
    chunk_seconds: float = 3.0,
    band: tuple[float, float] = (88.0e6, 108.0e6),
    hotspot_bias: float = 0.6,
    volume: int = DEFAULT_VOLUME,
    total_seconds: float | None = None,
    gate: bool = True,
    silence_dbfs: float = -50.0,
    max_flatness: float = 0.45,
    dedup: bool = True,
    dedup_window_seconds: float = 120.0,
    source: str = "sdr",
    on_chunk: Callable[[str, int], None] | None = None,
    on_transcript: Callable[[str, int, str], None] | None = None,
    on_profile: Callable[[str, int, dict, bool], None] | None = None,
    stop_event: threading.Event | None = None,
) -> None:
    """Hop across audio sources, playing each chunk live and transcribing it
    in the background so the next hop doesn't wait on the API response.

    `source` selects where chunks come from:
    - "sdr" (default): hops across `band` on the real FM channel grid, not
      arbitrary frequencies. If hotspots have been found via scan(), a
      hotspot_bias fraction of hops land on one of them (actual stations);
      the rest are fully random valid channels (static/other signals).
    - "stream": hops across the internet radio stations listed in
      streams.json (see load_streams()) instead of using the RTL-SDR --
      a non-hardware fallback, and talk/news stations give a much higher
      speech hit rate than music-heavy FM.

    When `gate` is True, each chunk is statistically profiled (see
    audiocheck.py) before being sent for transcription -- dead air and
    static are skipped without spending an API call. When `dedup` is True,
    each chunk is also checked against recent chunks (see dedup.py) --
    some stream relays intermittently loop a short segment instead of
    true live audio, and an exact repeat is skipped the same way. Either
    check can make `passed` False; `on_profile`, if set, is always called
    with the computed stats (including a "duplicate" key) regardless of
    pass/fail, for calibration/debugging.
    """
    if is_running() is not None:
        raise RuntimeError("live monitor is running -- run stop first")

    next_hop = _make_hop_picker(source, band, hotspot_bias)
    stop_event = stop_event or threading.Event()
    bytes_per_second = AUDIO_RATE_HZ * 2  # 16-bit mono
    chunk_bytes_target = int(bytes_per_second * chunk_seconds)

    player = subprocess.Popen(
        [
            "paplay",
            "--raw",
            f"--rate={AUDIO_RATE_HZ}",
            "--format=s16le",
            "--channels=1",
            "--client-name=spiritbox-sweep",
            f"--volume={volume}",
        ],
        stdin=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
    )
    assert player.stdin is not None

    from spiritbox import audiocheck, dedup, transcribe  # local import: keep OpenRouter optional for non-sweep commands

    dup_detector = dedup.DuplicateDetector(window_seconds=dedup_window_seconds) if dedup else None

    def _transcribe_and_report(wav_bytes: bytes, label: str, index: int) -> None:
        if on_transcript is None:
            return
        try:
            text = transcribe.transcribe_wav(wav_bytes)
        except Exception as exc:  # noqa: BLE001 -- surface any failure as a transcript line
            text = f"[transcription failed: {exc}]"
        on_transcript(label, index, text)

    # Stream sources need connection/buffering time beyond the raw chunk
    # duration; this bounds worst-case hang if a station stalls.
    max_chunk_wait = chunk_seconds + 5.0

    index = 0
    start_time = time.time()
    try:
        with ThreadPoolExecutor(max_workers=4) as executor:
            while not stop_event.is_set():
                if total_seconds is not None and time.time() - start_time >= total_seconds:
                    break

                label, cmd = next_hop()
                if on_chunk is not None:
                    on_chunk(label, index)

                pcm_bytes = _capture_chunk(cmd, chunk_bytes_target, player.stdin, max_chunk_wait)
                passed, _reason, stats = audiocheck.is_worth_transcribing(
                    pcm_bytes, AUDIO_RATE_HZ, silence_dbfs=silence_dbfs, max_flatness=max_flatness
                )
                is_dup = dup_detector.check(pcm_bytes) if dup_detector is not None else False
                stats["duplicate"] = is_dup
                transcribe_this = passed and not is_dup
                if on_profile is not None:
                    on_profile(label, index, stats, transcribe_this)

                if (gate and not passed) or (dedup and is_dup):
                    index += 1
                    continue

                executor.submit(_transcribe_and_report, _pcm_to_wav_bytes(pcm_bytes), label, index)
                index += 1
    finally:
        try:
            player.stdin.close()
        except OSError:
            pass
        _terminate(player.pid)


@dataclass
class _BufferedChunk:
    label: str
    pcm: bytes
    t_end: float
    is_duplicate: bool = False


class ScrubSession:
    """Continuously hops and plays live, like sweep(), but does NOT
    auto-transcribe every chunk. Instead it keeps a rolling buffer so the
    caller can mark() a recent stretch of audio on demand -- the user's ear
    decides what's worth sending to the API, not a statistical gate. This
    also means chunks can be much shorter (faster perceived hopping)
    without driving up API cost, since most hops are never transcribed.

    When `dedup` is True, each chunk is checked against recent chunks (see
    dedup.py) -- some stream relays intermittently loop a short segment
    instead of true live audio. Flagged chunks still play live (the user
    heard it happen regardless) but are excluded from mark()'s audio.
    """

    def __init__(
        self,
        chunk_seconds: float = 1.5,
        band: tuple[float, float] = (88.0e6, 108.0e6),
        hotspot_bias: float = 0.6,
        volume: int = DEFAULT_VOLUME,
        source: str = "sdr",
        buffer_seconds: float = 60.0,
        dedup: bool = True,
        dedup_window_seconds: float = 120.0,
        on_chunk: Callable[[str, int], None] | None = None,
        on_transcript: Callable[[str, str], None] | None = None,
        on_profile: Callable[[str, int, bool], None] | None = None,
    ) -> None:
        if is_running() is not None:
            raise RuntimeError("live monitor is running -- run stop first")

        self._next_hop = _make_hop_picker(source, band, hotspot_bias)
        self._chunk_seconds = chunk_seconds
        self._buffer_seconds = buffer_seconds
        self._on_chunk = on_chunk
        self._on_transcript = on_transcript
        self._on_profile = on_profile

        self._buffer: deque[_BufferedChunk] = deque()
        self._buffer_lock = threading.Lock()
        self._stop_event = threading.Event()
        self._thread: threading.Thread | None = None
        self._executor = ThreadPoolExecutor(max_workers=4)
        self._index = 0

        from spiritbox import dedup as dedup_module  # local import: keep OpenRouter optional for non-scrub commands
        from spiritbox import transcribe

        self._transcribe = transcribe
        self._dup_detector = dedup_module.DuplicateDetector(window_seconds=dedup_window_seconds) if dedup else None

        self._player = subprocess.Popen(
            [
                "paplay",
                "--raw",
                f"--rate={AUDIO_RATE_HZ}",
                "--format=s16le",
                "--channels=1",
                "--client-name=spiritbox-scrub",
                f"--volume={volume}",
            ],
            stdin=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
        )
        assert self._player.stdin is not None

    def start(self) -> None:
        self._thread = threading.Thread(target=self._run, daemon=True)
        self._thread.start()

    def _run(self) -> None:
        bytes_per_second = AUDIO_RATE_HZ * 2
        chunk_bytes_target = int(bytes_per_second * self._chunk_seconds)
        max_chunk_wait = self._chunk_seconds + 5.0

        while not self._stop_event.is_set():
            label, cmd = self._next_hop()
            if self._on_chunk is not None:
                self._on_chunk(label, self._index)

            pcm = _capture_chunk(cmd, chunk_bytes_target, self._player.stdin, max_chunk_wait)
            t_end = time.time()
            is_dup = self._dup_detector.check(pcm) if self._dup_detector is not None else False
            if self._on_profile is not None:
                self._on_profile(label, self._index, is_dup)

            with self._buffer_lock:
                self._buffer.append(_BufferedChunk(label=label, pcm=pcm, t_end=t_end, is_duplicate=is_dup))
                cutoff = t_end - self._buffer_seconds
                while self._buffer and self._buffer[0].t_end < cutoff:
                    self._buffer.popleft()

            self._index += 1

    def mark(self, window_seconds: float = 5.0) -> None:
        """Grab roughly the last `window_seconds` of buffered audio and
        submit it for transcription in the background."""
        cutoff = time.time() - window_seconds
        with self._buffer_lock:
            chunks = [c for c in self._buffer if c.t_end >= cutoff]

        if not chunks:
            if self._on_transcript is not None:
                self._on_transcript("(nothing buffered yet)", "")
            return

        clean_chunks = [c for c in chunks if not c.is_duplicate]
        if not clean_chunks:
            if self._on_transcript is not None:
                self._on_transcript("(skipped: buffered audio was all duplicate/looping)", "")
            return
        chunks = clean_chunks

        pcm = b"".join(c.pcm for c in chunks)
        target_bytes = int(window_seconds * AUDIO_RATE_HZ * 2)
        if len(pcm) > target_bytes:
            pcm = pcm[-target_bytes:]

        labels: list[str] = []
        for c in chunks:
            if not labels or labels[-1] != c.label:
                labels.append(c.label)
        label_summary = " -> ".join(labels)

        self._executor.submit(self._transcribe_and_report, _pcm_to_wav_bytes(pcm), label_summary)

    def _transcribe_and_report(self, wav_bytes: bytes, label_summary: str) -> None:
        if self._on_transcript is None:
            return
        try:
            text = self._transcribe.transcribe_wav(wav_bytes)
        except Exception as exc:  # noqa: BLE001 -- surface any failure as a transcript line
            text = f"[transcription failed: {exc}]"
        self._on_transcript(label_summary, text)

    def stop(self) -> None:
        self._stop_event.set()
        if self._thread is not None:
            self._thread.join(timeout=5)
        self._executor.shutdown(wait=True)
        try:
            self._player.stdin.close()
        except OSError:
            pass
        _terminate(self._player.pid)
